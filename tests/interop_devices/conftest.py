"""Interoperability against independent DICOM implementations.

AranMed's SCP runs in-process; the other side is **dcmtk** (OFFIS, C++)
command-line tools and a real **Orthanc** server, so nothing on the far end
shares code with pynetdicom. Each test emulates one documented vendor
behaviour (transfer syntaxes proposed, PDU size, association pattern,
character set) and is tagged with ``@pytest.mark.device(vendor, service)``;
the run writes a compatibility matrix when ``INTEROP_MATRIX_OUT`` is set.
"""
from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path

import pytest

from tests.functional.conftest import clinical_env, free_port  # noqa: F401

pytestmark = pytest.mark.interop

SCP_AE = "TESTPACS"
DCMTK = all(shutil.which(t) for t in ("echoscu", "storescu", "findscu", "movescu", "getscu",
                                       "storescp"))
CORPUS = Path(os.environ.get("DICOM_CORPUS_DIR", "/var/tmp/dicom-corpus/pydicom-data/data_store/data"))

# Devices registered on the PACS for these tests: AE title -> description.
DEVICES = {
    "SIEMENS_CT": "Siemens SOMATOM (syngo CT VB20A profile)",
    "CANON_CT": "Canon Aquilion ONE (V1.5 profile)",
    "EPIQ_US": "Philips EPIQ ultrasound (R9 profile)",
    "HOLOGIC_MG": "Hologic Selenia Dimensions (v1.12 profile)",
    "CR_ROOM": "Carestream DirectView CR / DRX",
    "CONSOLE": "Reading workstation (Q/R SCU + Storage SCP)",
    "CORPUS": "Real-file corpus sender",
}


def run(cmd: list[str], timeout: float = 120, cwd=None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, cwd=cwd)


@pytest.fixture
def scp(clinical_env, monkeypatch):  # noqa: F811
    """Running AranMed SCP with every emulated device registered."""
    if not DCMTK:
        pytest.skip("dcmtk command-line tools not installed")
    from clinicaldb import facilities
    from pacs import dimse, nodes
    facilities.seed_local()
    monkeypatch.setenv("PACS_EXTRA_SOP_CLASSES", "1.2.840.113681.1.2.1")  # vendor-private (Hologic-style)
    console_port = free_port()
    for ae, name in DEVICES.items():
        extra = {"charset": "ISO_IR 100", "name_romanize": True} if ae == "CANON_CT" else {}
        nodes.save({"name": name, "kind": "dimse", "ae_title": ae, "host": "127.0.0.1",
                    "port": console_port if ae == "CONSOLE" else free_port(),
                    "allow_store": True, "allow_query": True, "allow_retrieve": True,
                    "is_move_destination": ae == "CONSOLE", **extra})
    server = dimse.DimseServer(ae_title=SCP_AE, bind="127.0.0.1", port=0).start()
    yield {"port": server.port, "console_port": console_port, "tmp": clinical_env}
    server.stop()


# ---------------------------------------------------------------- matrix
_results: list[dict] = []


def pytest_runtest_logreport(report):
    if report.when != "call" and not (report.when == "setup" and report.skipped):
        return
    m = getattr(report, "_device", None)
    if m:
        _results.append({**m, "test": report.nodeid.split("::")[-1], "outcome": report.outcome})


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    rep = outcome.get_result()
    mark = item.get_closest_marker("device")
    if mark:
        rep._device = {"vendor": mark.kwargs.get("vendor", ""), "service": mark.kwargs.get("service", "")}


def pytest_sessionfinish(session, exitstatus):
    out = os.environ.get("INTEROP_MATRIX_OUT")
    if not out or not _results:
        return
    icon = {"passed": "PASS", "failed": "FAIL", "skipped": "SKIP"}
    lines = ["# Imaging-device compatibility matrix", "",
             "Generated by `tests/interop_devices` — AranMed's SCP against independent DICOM "
             "implementations (dcmtk 3.6 command-line tools, Orthanc server) emulating "
             "documented vendor behaviour.", "",
             "| Vendor / device profile | DICOM service | Test | Result |", "|---|---|---|---|"]
    for r in _results:
        lines.append(f"| {r['vendor']} | {r['service']} | `{r['test']}` | {icon.get(r['outcome'], r['outcome'])} |")
    p = sum(r["outcome"] == "passed" for r in _results)
    lines += ["", f"**{p} of {len(_results)} passed.**", ""]
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(lines), encoding="utf-8")
